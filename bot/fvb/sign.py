"""Signers for a fair-value packet.

secp256k1 signatures are over the EIP-712 digest. ed25519 signatures are
over the keccak of the same field encoding. ``ml-dsa`` and ``falcon`` are
recognised and rejected: this build does not carry a post-quantum
verifier, and it will not pretend a packet checked out.

A mainnet chain id or cluster is refused before any signature is made.
Keys here are generated by the caller. Nothing in this module reads a
key off disk.
"""
from __future__ import annotations

import hashlib
from dataclasses import dataclass

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, ed25519, utils
from cryptography.hazmat.primitives.asymmetric.ec import EllipticCurvePrivateKey

from bot.fvb.chains import MainnetRefused, assert_testnet_chain, assert_testnet_cluster
from bot.fvb.keccak import keccak256
from bot.fvb.packet import SESSION_CODE

_N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
_P = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F
_GX = 0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798
_GY = 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8

_DOMAIN = "EIP712Domain(string name,string version,uint256 chainId,address verifyingContract)"
_PACKET = (
    "FVBPacket(bytes32 symbol,uint256 fv,uint256 bandLo,uint256 bandHi,"
    "uint8 session,bool confirmed,uint64 ts,uint32 version,bytes32 nextEpoch)"
)
_NAME = b"Fair-Value Bridge"
_VERSION = b"1"

ACCEPTED_SCHEMES = frozenset({"secp256k1", "ed25519"})
REJECTED_SCHEMES = frozenset({"ml-dsa", "falcon", "dilithium"})


class SchemeRejected(Exception):
    """The scheme is not one this build will sign or verify."""


def require_scheme(name: str) -> str:
    key = name.strip().lower()
    if key in REJECTED_SCHEMES or key not in ACCEPTED_SCHEMES:
        raise SchemeRejected(key)
    return key


def commit_pubkey(public: bytes) -> str:
    """SHA-256 hex of a public key. The next-epoch commitment."""
    return hashlib.sha256(public).hexdigest()


def _u256(n: int) -> bytes:
    if n < 0:
        raise ValueError("negative word")
    return int(n).to_bytes(32, "big")


def _addr(raw: bytes) -> bytes:
    if len(raw) != 20:
        raise ValueError("address")
    return raw.rjust(32, b"\x00")


def symbol_word(symbol: str) -> bytes:
    raw = symbol.encode("utf-8")
    if len(raw) > 32:
        raise ValueError("symbol")
    return raw.ljust(32, b"\x00")


@dataclass(frozen=True)
class PacketFields:
    symbol: bytes
    fv: int
    band_lo: int
    band_hi: int
    session: int
    confirmed: bool
    ts: int
    version: int
    next_epoch: bytes

    def words(self) -> bytes:
        if len(self.symbol) != 32 or len(self.next_epoch) != 32:
            raise ValueError("word")
        if min(self.fv, self.band_lo, self.band_hi) <= 0:
            raise ValueError("price")
        return b"".join((
            self.symbol,
            _u256(self.fv),
            _u256(self.band_lo),
            _u256(self.band_hi),
            _u256(self.session),
            _u256(1 if self.confirmed else 0),
            _u256(self.ts),
            _u256(self.version),
            self.next_epoch,
        ))


def session_code(name: str) -> int:
    code = SESSION_CODE.get(name)
    if code is None:
        raise ValueError("session")
    return code


def packet_words(fields: PacketFields) -> bytes:
    return fields.words()


def eip712_digest(fields: PacketFields, chain_id: int, verifying_contract: bytes) -> bytes:
    assert_testnet_chain(chain_id)
    struct_hash = keccak256(keccak256(_PACKET.encode("ascii")) + fields.words())
    domain = keccak256(b"".join((
        keccak256(_DOMAIN.encode("ascii")),
        keccak256(_NAME),
        keccak256(_VERSION),
        _u256(chain_id),
        _addr(verifying_contract),
    )))
    return keccak256(b"\x19\x01" + domain + struct_hash)


def ed25519_message(fields: PacketFields) -> bytes:
    return keccak256(fields.words())


@dataclass(frozen=True)
class PacketSignature:
    scheme: str
    signer_id: str
    public: bytes
    signature: bytes


class Signer:
    """One ephemeral key. Constructed by ``mint_signer``."""

    def __init__(self, signer_id: str, scheme: str, private: object) -> None:
        self.signer_id = signer_id
        self.scheme = require_scheme(scheme)
        self._private = private

    @staticmethod
    def mint_signer(signer_id: str, scheme: str) -> "Signer":
        chosen = require_scheme(scheme)
        if chosen == "secp256k1":
            return Signer(signer_id, chosen, ec.generate_private_key(ec.SECP256K1()))
        return Signer(signer_id, chosen, ed25519.Ed25519PrivateKey.generate())

    def public_key_bytes(self) -> bytes:
        if self.scheme == "ed25519":
            private = self._private
            assert isinstance(private, ed25519.Ed25519PrivateKey)
            return private.public_key().public_bytes(
                serialization.Encoding.Raw, serialization.PublicFormat.Raw,
            )
        private = self._private
        assert isinstance(private, EllipticCurvePrivateKey)
        nums = private.public_key().public_numbers()
        return nums.x.to_bytes(32, "big") + nums.y.to_bytes(32, "big")

    def sign_fields(self, fields: PacketFields, *, chain_id: int | None,
                    verifying_contract: bytes) -> PacketSignature:
        message = _message(self.scheme, fields, chain_id, verifying_contract)
        if self.scheme == "ed25519":
            private = self._private
            assert isinstance(private, ed25519.Ed25519PrivateKey)
            sig = private.sign(message)
        else:
            sig = _sign_secp(self._private, message)
        return PacketSignature(self.scheme, self.signer_id, self.public_key_bytes(), sig)


def _message(scheme: str, fields: PacketFields, chain_id: int | None,
             verifying_contract: bytes) -> bytes:
    if scheme == "secp256k1":
        if chain_id is None:
            raise MainnetRefused("no chain")
        return eip712_digest(fields, chain_id, verifying_contract)
    if scheme == "ed25519":
        return ed25519_message(fields)
    raise SchemeRejected(scheme)


def _sign_secp(private: object, digest: bytes) -> bytes:
    assert isinstance(private, EllipticCurvePrivateKey)
    der = private.sign(digest, ec.ECDSA(utils.Prehashed(hashes.SHA256())))
    r, s = utils.decode_dss_signature(der)
    if s > _N // 2:
        s = _N - s
    nums = private.public_key().public_numbers()
    v = _recovery_bit(digest, r, s, nums.x, nums.y)
    if v is None:
        raise SchemeRejected("recovery")
    return r.to_bytes(32, "big") + s.to_bytes(32, "big") + bytes((v,))


def signature_ok(packet: PacketSignature, fields: PacketFields, *,
                 chain_id: int | None, verifying_contract: bytes) -> bool:
    try:
        scheme = require_scheme(packet.scheme)
    except SchemeRejected:
        return False
    message = _message(scheme, fields, chain_id, verifying_contract)
    if scheme == "ed25519":
        if len(packet.public) != 32 or len(packet.signature) != 64:
            return False
        try:
            ed25519.Ed25519PublicKey.from_public_bytes(packet.public).verify(
                packet.signature, message)
        except Exception:
            return False
        return True
    if len(packet.public) != 64 or len(packet.signature) != 65:
        return False
    r = int.from_bytes(packet.signature[:32], "big")
    s = int.from_bytes(packet.signature[32:64], "big")
    if r <= 0 or r >= _N or s <= 0 or s > _N // 2:
        return False
    try:
        public = ec.EllipticCurvePublicNumbers(
            int.from_bytes(packet.public[:32], "big"),
            int.from_bytes(packet.public[32:], "big"),
            ec.SECP256K1(),
        ).public_key()
        public.verify(
            utils.encode_dss_signature(r, s), message,
            ec.ECDSA(utils.Prehashed(hashes.SHA256())),
        )
    except Exception:
        return False
    return True


class Committee:
    """k-of-n. The default the bridge ships is 3 of 5."""

    def __init__(self, signers: list[Signer], *, threshold: int,
                 verifying_contract: bytes, chain_id: int | None = None,
                 cluster: str | None = None) -> None:
        if chain_id is None and cluster is None:
            raise MainnetRefused("no network")
        if chain_id is not None:
            assert_testnet_chain(chain_id)
        if cluster is not None:
            assert_testnet_cluster(cluster)
        if threshold < 1 or len(signers) < threshold:
            raise ValueError("threshold")
        ids = [s.signer_id for s in signers]
        if len(set(ids)) != len(ids):
            raise ValueError("signer id")
        schemes = {s.scheme for s in signers}
        if len(schemes) != 1:
            raise SchemeRejected("mixed")
        self.signers = list(signers)
        self.threshold = threshold
        self.chain_id = chain_id
        self.cluster = cluster
        self.verifying_contract = verifying_contract
        self._next: dict[str, str] = {}

    def commit_next_key(self, signer_id: str, public: bytes) -> str:
        digest = commit_pubkey(public)
        self._next[signer_id] = digest
        return digest

    def rotate_signer(self, signer_id: str, new_signer: Signer) -> None:
        """Replace a signer only when the new key matches the commitment."""
        if new_signer.scheme != self.signers[0].scheme:
            raise SchemeRejected(new_signer.scheme)
        want = self._next.get(signer_id)
        if want is None or commit_pubkey(new_signer.public_key_bytes()) != want:
            raise SchemeRejected("commitment")
        replaced = False
        updated: list[Signer] = []
        for signer in self.signers:
            if signer.signer_id == signer_id:
                updated.append(new_signer)
                replaced = True
            else:
                updated.append(signer)
        if not replaced:
            raise SchemeRejected("signer")
        self.signers = updated

    def sign_packet(self, fields: PacketFields) -> list[PacketSignature]:
        return [
            signer.sign_fields(
                fields, chain_id=self.chain_id, verifying_contract=self.verifying_contract,
            )
            for signer in self.signers
        ]

    def verify_packet(self, fields: PacketFields, signatures: list[PacketSignature]) -> bool:
        seen: set[bytes] = set()
        good = 0
        for packet in signatures:
            if packet.public in seen:
                continue
            if packet.scheme != self.signers[0].scheme:
                return False
            seen.add(packet.public)
            if not signature_ok(
                packet, fields, chain_id=self.chain_id,
                verifying_contract=self.verifying_contract,
            ):
                return False
            good += 1
        return good >= self.threshold


def _inv(n: int, mod: int) -> int:
    return pow(n, -1, mod)


def _add(p: tuple[int, int] | None, q: tuple[int, int] | None) -> tuple[int, int] | None:
    if p is None:
        return q
    if q is None:
        return p
    x1, y1 = p
    x2, y2 = q
    if x1 == x2 and (y1 + y2) % _P == 0:
        return None
    if x1 == x2 and y1 == y2:
        lam = (3 * x1 * x1 * _inv(2 * y1, _P)) % _P
    else:
        lam = ((y2 - y1) * _inv((x2 - x1) % _P, _P)) % _P
    x3 = (lam * lam - x1 - x2) % _P
    y3 = (lam * (x1 - x3) - y1) % _P
    return x3, y3


def _mul(k: int, point: tuple[int, int] | None) -> tuple[int, int] | None:
    acc: tuple[int, int] | None = None
    base = point
    while k:
        if k & 1:
            acc = _add(acc, base)
        base = _add(base, base)
        k >>= 1
    return acc


def _decompress(x: int, y_odd: bool) -> tuple[int, int] | None:
    y2 = (pow(x, 3, _P) + 7) % _P
    y = pow(y2, (_P + 1) // 4, _P)
    if (y * y) % _P != y2:
        return None
    if (y % 2 == 1) != y_odd:
        y = _P - y
    return x, y


def _recover_point(digest: bytes, r: int, s: int, recid: int) -> tuple[int, int] | None:
    x = r + (recid // 2) * _N
    if x >= _P:
        return None
    point = _decompress(x, recid % 2 == 1)
    if point is None:
        return None
    e = int.from_bytes(digest, "big")
    rinv = _inv(r, _N)
    s_r = _mul(s, point)
    e_g = _mul(e % _N, (_GX, _GY))
    if e_g is None or s_r is None:
        return None
    minus = (e_g[0], (_P - e_g[1]) % _P)
    return _mul(rinv, _add(s_r, minus))


def _recovery_bit(digest: bytes, r: int, s: int, x: int, y: int) -> int | None:
    for recid in (0, 1):
        point = _recover_point(digest, r, s, recid)
        if point is not None and point[0] == x and point[1] == y:
            return 27 + recid
    return None
