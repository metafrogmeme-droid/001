#!/usr/bin/env node
'use strict';
/**
 * The Pi Browser app's words, one chunk per language.
 *
 * NOT THE SITE'S DICTIONARY (build_i18n.js). That one carries every page's
 * strings, the presale's among them, and the Pi app may load none of it. This
 * builds a small table of the Pi app's own sentences.
 *
 * THE SENTENCES ARE READ FROM THE CODE, not listed by hand. Every script the
 * Pi page loads (routes/piapp.js SCRIPTS, the one list) is read with its
 * comments blanked, and three shapes are collected:
 *
 *   T('English sentence')            the Pi modules' own words
 *   label: 'Tab'                     a tab block's label (arena-session.js
 *                                    draws it through T)
 *   tr('duel.key', 'English')        the Duel renderer's words; on the Pi page
 *                                    its lookup is T(English) (pi-duel.js TR)
 *
 * A sentence that leaves the code leaves the table; a sentence that enters it
 * is missing in every language until someone translates it, and --check fails
 * until then.
 * THE SERVER'S OWN SENTENCES TOO (SERVER_SOURCES). The Pi app prints some
 * sentences the server sent: a refusal (`error: 'That handle is taken — try
 * another.'`) and the coach's four fixed answers (bot/web/pi_coach.py). They
 * were English in every language. They are collected from the code that says
 * them, so the English stays in one place, and the Pi app passes what it was
 * sent through T: a sentence the table knows is translated, any other prints
 * as sent. A refusal built from a template (a price, a list of words) is not a
 * literal and stays English.
 *
 * THE TRANSLATIONS are app/i18n/pi/<code>.pairs.json, a list of [english, text]
 * pairs (pairs, not an object, for the reason build_i18n.js gives: a `"name":
 * "value"` line is the shape a secret scanner keys on). A Duel sentence that a
 * language's file leaves out borrows the site's translation of the same key
 * (public/js/i18n.js), but only while the site's English for that key is the
 * English the renderer falls back to: a translation of a different sentence
 * is not a translation of this one.
 *
 * EVERY {placeholder} OF THE ENGLISH MUST BE IN THE TRANSLATION, and no other:
 * a translation that drops {price} would print a sentence with no price in
 * it, and one that invents {pirce} would print the braces.
 *
 *   node app/scripts/build_pi_i18n.js            # write public/js/pi-i18n/<code>.js
 *   node app/scripts/build_pi_i18n.js --check    # exit 1 on a missing, stale or
 *                                                # broken entry, or a chunk that would change
 *   node app/scripts/build_pi_i18n.js --missing vi   # the English vi lacks, as JSON
 */
const fs = require('fs');
const path = require('path');

const APP = path.join(__dirname, '..');
const PUB = path.join(APP, 'public');
const SRC_DIR = path.join(APP, 'i18n', 'pi');
const OUT_DIR = path.join(PUB, 'js', 'pi-i18n');
/**
 * `<code>.pairs.json`, not `<code>.json`: `id.json` is the name of a Solana
 * keypair, and the repo's .gitignore denies it everywhere, with no exception.
 * Indonesian's source was named that once and never reached a commit; the
 * build passed on the copy in the working tree and failed in CI. A test now
 * asks git whether any source is ignored.
 */
const SUFFIX = '.pairs.json';
const BANNER = '// GENERATED by app/scripts/build_pi_i18n.js from app/i18n/pi/{code}.pairs.json — edit the source, not this file.';

const { codeOnly } = require('../test/helpers/code_only');
const PiI18n = require('../public/js/pi-i18n.js');

const LIT = "'((?:[^'\\\\\\n]|\\\\.)*)'";
const T_RE = new RegExp('(?<![\\w$.])T\\(\\s*' + LIT, 'g');
const LABEL_RE = new RegExp('(?<![\\w$.])label:\\s*' + LIT, 'g');
const TR_RE = new RegExp("(?<![\\w$.])tr\\(\\s*'([\\w.]+)'\\s*,\\s*" + LIT, 'g');

/**
 * The server code whose sentences reach the Pi app as they were sent: the
 * Duel call's refusals (routes/duel.js passes placePick's `error` through),
 * the Leaders name's (routes/leaderboard.js) and the coach's fixed answers,
 * which the bot's gateway sends as `reply_html` with an intent naming each
 * (bot/web/user_gateway.py). `shape` is how each file states them.
 */
const SERVER_SOURCES = [
  { file: path.join(APP, 'lib', 'duel_service.js'), shape: 'error' },
  { file: path.join(APP, 'routes', 'leaderboard.js'), shape: 'error' },
  { file: path.join(APP, '..', 'bot', 'web', 'pi_coach.py'), shape: 'py_answers' },
];
/** The coach's fixed answers, by the names bot/web/pi_coach.py gives them. */
const PY_ANSWERS = ['TOKEN_ANSWER', 'NO_FEED_ANSWER', 'WITHHELD_ANSWER', 'UNAVAILABLE_ANSWER'];
const ERROR_RE = new RegExp('(?<![\\w$.])error:\\s*' + LIT, 'g');

/** A single-quoted literal's body, unescaped. */
function unquote(body) {
  return body.replace(/\\(u\{[0-9a-fA-F]+\}|u[0-9a-fA-F]{4}|x[0-9a-fA-F]{2}|[\s\S])/g, (m, e) => {
    if (e[0] === 'u') return String.fromCodePoint(parseInt(e[1] === '{' ? e.slice(2, -1) : e.slice(1), 16));
    if (e[0] === 'x' && e.length === 3) return String.fromCharCode(parseInt(e.slice(1), 16));
    return { n: '\n', t: '\t', r: '\r' }[e] || e;
  });
}

/** The Pi page's own scripts, in load order, as paths on disk. */
function scriptFiles() {
  const { SCRIPTS } = require('../routes/piapp');
  return SCRIPTS.map((s) => s.split('?')[0])
    .filter((s) => s.startsWith('/js/') && !s.startsWith('/js/pi-i18n'))
    .map((s) => path.join(PUB, s));
}

/**
 * Every sentence the Pi app draws through T, as a Map of english ->
 * { files: Set, keys: Set } (keys: the Duel renderer's keys for it).
 */
function sentences(files, { includeServer = false } = {}) {
  const list = files === undefined ? scriptFiles() : files;
  const out = new Map();
  const add = (en, file, key) => {
    if (!en) return;
    const rec = out.get(en) || { files: new Set(), keys: new Set() };
    rec.files.add(path.relative(APP, file));
    if (key) rec.keys.add(key);
    out.set(en, rec);
  };
  for (const file of list) {
    const src = codeOnly(fs.readFileSync(file, 'utf8'));
    let m;
    T_RE.lastIndex = 0;
    while ((m = T_RE.exec(src))) add(unquote(m[1]), file);
    // A tab's label is a T on the session's side; only the Pi blocks declare tabs.
    if (/^pi-/.test(path.basename(file))) {
      LABEL_RE.lastIndex = 0;
      while ((m = LABEL_RE.exec(src))) add(unquote(m[1]), file);
    }
    TR_RE.lastIndex = 0;
    while ((m = TR_RE.exec(src))) add(unquote(m[2]), file, m[1]);
  }
  if (files === undefined || includeServer) {
    for (const [en, file] of serverSentences()) add(en, file);
  }
  return out;
}

/**
 * The server's sentences, [english, file] in source order. A Python answer is
 * a parenthesised run of adjacent "..." pieces; one that is missing, or that
 * carries an escape this reader does not decode, throws rather than
 * collecting a sentence the server never sends.
 */
function serverSentences(sources = SERVER_SOURCES) {
  const out = [];
  for (const { file, shape } of sources) {
    const raw = fs.readFileSync(file, 'utf8');
    if (shape === 'error') {
      const src = codeOnly(raw);
      let m;
      ERROR_RE.lastIndex = 0;
      while ((m = ERROR_RE.exec(src))) out.push([unquote(m[1]), file]);
    } else if (shape === 'py_answers') {
      for (const name of PY_ANSWERS) {
        const m = new RegExp('^' + name + ' = \\(((?:\\s*"[^"\\\\\\n]*")+)\\s*\\)', 'm').exec(raw);
        if (!m) throw new Error(`${path.relative(APP, file)}: no ${name} = ("…") to read`);
        out.push([[...m[1].matchAll(/"([^"]*)"/g)].map((p) => p[1]).join(''), file]);
      }
    } else {
      throw new Error(`unknown shape ${shape}`);
    }
  }
  return out;
}

function placeholders(s) {
  return [...new Set((String(s).match(/\{\w+\}/g) || []))].sort();
}

function readPairs(code, dir = SRC_DIR) {
  const file = path.join(dir, `${code}${SUFFIX}`);
  if (!fs.existsSync(file)) return { file, pairs: [] , absent: true };
  const raw = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (!Array.isArray(raw)) throw new Error(`${path.relative(APP, file)}: expected a list of [english, text] pairs`);
  return { file, pairs: raw };
}

/**
 * { chunks: {code: text}, problems: [string], missing: {code: [english]} } —
 * pure, from the code and the sources on disk. A test may hand it another
 * source directory or site table (`srcDir`, `site`) to drive a broken entry.
 */
function build({ srcDir = SRC_DIR, site = require('../public/js/i18n.js').STRINGS || {} } = {}) {
  const said = sentences();
  const problems = [];
  const missing = {};
  const chunks = {};
  const codes = PiI18n.CODES.filter((c) => c !== 'en');
  for (const code of codes) {
    const { file, pairs, absent } = readPairs(code, srcDir);
    const rel = path.relative(APP, file);
    if (absent) problems.push(`${rel}: no translations for ${code}`);
    const own = new Map();
    pairs.forEach((p, i) => {
      if (!Array.isArray(p) || p.length !== 2 || typeof p[0] !== 'string' || typeof p[1] !== 'string' || !p[1].trim()) {
        problems.push(`${rel}[${i}]: not an [english, text] pair`);
        return;
      }
      if (own.has(p[0])) problems.push(`${rel}: "${p[0]}" is translated twice`);
      own.set(p[0], p[1]);
    });
    for (const en of own.keys()) {
      if (!said.has(en)) problems.push(`${rel}: "${en}" is no longer in the Pi app (stale)`);
    }
    const table = [];
    missing[code] = [];
    for (const [en, rec] of said) {
      let text = own.get(en);
      if (text === undefined) {
        for (const key of rec.keys) {
          const entry = site[key];
          if (entry && entry.en === en && typeof entry[code] === 'string' && entry[code].trim()) { text = entry[code]; break; }
        }
      }
      if (text === undefined) { missing[code].push(en); continue; }
      const want = placeholders(en).join(' ');
      const got = placeholders(text).join(' ');
      if (want !== got) problems.push(`${code}: "${en}" has {${want}} but its translation has {${got}}`);
      table.push([en, text]);
    }
    if (missing[code].length) problems.push(`${code}: ${missing[code].length} sentence(s) not translated`);
    table.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
    chunks[code] = BANNER.replace('{code}', code) + '\n'
      + '(function () {\n'
      + "  var I = typeof window !== 'undefined' && window.RCPiI18n;\n"
      + '  if (!I) return;\n'
      + `  I.add(${JSON.stringify(code)}, [\n`
      + table.map((p) => '    ' + JSON.stringify(p) + ',\n').join('')
      + '  ]);\n'
      + '}());\n';
  }
  return { chunks, problems, missing, sentences: said };
}

function main(argv) {
  const at = argv.indexOf('--missing');
  if (at >= 0) {
    const code = argv[at + 1];
    const out = build();
    process.stdout.write(JSON.stringify(out.missing[code] || [], null, 1) + '\n');
    return 0;
  }
  const check = argv.includes('--check');
  const out = build();
  let bad = out.problems.length > 0;
  for (const p of out.problems) process.stderr.write(p + '\n');
  for (const [code, text] of Object.entries(out.chunks)) {
    const file = path.join(OUT_DIR, `${code}.js`);
    const now = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (now === text) continue;
    if (check) {
      process.stderr.write(`${path.relative(APP, file)} is not the built chunk: run node app/scripts/build_pi_i18n.js\n`);
      bad = true;
    } else {
      fs.mkdirSync(OUT_DIR, { recursive: true });
      fs.writeFileSync(file, text);
    }
  }
  // A chunk for a language the app no longer lists is stale too.
  if (fs.existsSync(OUT_DIR)) {
    for (const f of fs.readdirSync(OUT_DIR)) {
      if (!out.chunks[f.replace(/\.js$/, '')]) {
        process.stderr.write(`public/js/pi-i18n/${f}: no such language in pi-i18n.js\n`);
        bad = true;
      }
    }
  }
  if (!check) process.stdout.write(`pi-i18n: ${out.sentences.size} sentences, ${Object.keys(out.chunks).length} languages\n`);
  return bad ? 1 : 0;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));

module.exports = { build, sentences, serverSentences, scriptFiles, placeholders, unquote, main, SRC_DIR, SUFFIX,
  SERVER_SOURCES, PY_ANSWERS };
