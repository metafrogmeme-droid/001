"""Three keys protect three stores, and the product must say which is which.

The operator's report was "WEB_CREDS_KEY is unset, so that Bybit key remains
in plaintext". The first half is a fact; the "so" was the product's fault.
`boot_health.py` described WEB_CREDS_KEY as "decrypting stored per-user
exchange keys", so the boot WARNING that names it read as "the keys users
linked are sitting unencrypted". They are not:

  * keys users link (/connect, the website)  → Fernet under the MASTER key,
                                               whatever else is set;
  * a website submission in transit to the bot → SEALED to this bot's own key,
                                               or refused (nothing is queued);
  * the operator's own venue keys            → .env, mirrored encrypted into
                                               the vault; the .env copy stays
                                               until it is set through
                                               /setexchange and deleted.

The third line is where a Bybit key really can remain in the clear, and it
has nothing to do with WEB_CREDS_KEY. So: the boot line now prints the effect
beside the name, /vault says what encrypts what, and /setexchange takes Bybit
and BingX so the .env copy can be retired (tests/test_setexchange_admin.py).

THE SECOND LINE CHANGED THE FOLLOWING WEEK, and it changed what this file has
to hold. The report behind it was the other half of the same complaint — the
website's connect form did not save anything — and the cause was that
WEB_CREDS_KEY had to be generated by hand and set in TWO deployments before a
submission could be protected at all. It is sealed to the bot's own published
key now (`bot/utils/creds_sealing.py`), with nothing to configure. So the
honest thing to say about that variable is no longer "a surface is broken"; it
is that it is legacy and unset is the ordinary state. A warning that names a
surface which is in fact working is how an operator learns to skip the next
warning — the same misreading, one door along.
"""
from __future__ import annotations

from types import SimpleNamespace

import pytest

from bot.core import boot_health as bh

# ── the boot line ──────────────────────────────────────────────────────────

def test_every_important_variable_states_its_effect():
    for name in bh.IMPORTANT_ENV:
        assert name in bh.IMPORTANT_ENV_EFFECT and bh.IMPORTANT_ENV_EFFECT[name].strip(), name


def test_the_boot_line_prints_the_effect_beside_the_name():
    msg = bh.format_preflight(bh.env_preflight({"TELEGRAM_BOT_TOKEN": "t" * 40}))
    for name, effect in bh.IMPORTANT_ENV_EFFECT.items():
        assert f"{name} — {effect}" in msg, name


def test_the_legacy_shared_key_is_not_reported_as_a_broken_surface():
    """An unset WEB_CREDS_KEY breaks nothing on the connect form any more, so
    the boot line must not list it. Listing it would be the 2026-09-06
    misreading in a milder form: a name printed under "a web surface will be
    degraded" for a surface that works."""
    assert "WEB_CREDS_KEY" not in bh.IMPORTANT_ENV
    assert "WEB_CREDS_KEY" not in bh.IMPORTANT_ENV_EFFECT
    msg = bh.format_preflight(bh.env_preflight({"TELEGRAM_BOT_TOKEN": "t" * 40}))
    assert "WEB_CREDS_KEY" not in msg


def test_the_variable_the_connect_form_actually_needs_says_so():
    """Something still gates it — the SYNC CHANNEL, which is what carries the
    bot's sealing key to the website. Dropping the old line without naming its
    replacement would leave the one variable that can turn the form off
    described as a dashboard concern."""
    effect = bh.IMPORTANT_ENV_EFFECT["BOT_SYNC_SECRET"]
    assert "connect form" in effect and "sealing key" in effect
    assert "stored per-user" not in effect, "the 2026-09-06 misreading, back"


