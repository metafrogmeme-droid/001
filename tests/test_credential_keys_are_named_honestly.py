# ── the website half: unset means refused, never plaintext ─────────────────

def _submit_handler_code() -> str:
    """`POST /api/credentials`, comments stripped.

    Stripped because the handler's own comments name `sealJSON` and
    `encryptJSON` in prose — the standing rule, and this scan would otherwise
    find the explanation and read it as the code.
    """
    from pathlib import Path

    from tests.source_scan import js_code_only
    route = js_code_only(Path("app/routes/credentials.js").read_text(encoding="utf-8"))
    i = route.index("router.post('/'")
    return route[i:route.index("router.delete('/'", i)]


def test_the_website_refuses_rather_than_queues_what_nobody_can_open():
    """Pinned from the Node side by reading, because the claim on the /vault
    card ("the website's connect form refuses until it can") is only true
    while this holds — and it is a claim made in Python about JavaScript.

    WIRING ONLY, deliberately. The behaviour — the 503, its reason code, the
    absence of a queued row — is exercised end to end in
    `app/test/creds_sealing.test.js`. What a source scan adds is the ORDER: the
    gate must be reached before anything is protected, which is the property
    that decides whether a submission can be stored under a path the gate did
    not approve.
    """
    body = _submit_handler_code()
    gate = body.index("await protection()")
    assert "prot.mode === 'off'" in body
    assert "503" in body[gate:][:400]
    # Nothing is protected — by either path — before the gate has answered.
    for fn in ("sealJSON(", "encryptJSON("):
        assert gate < body.index(fn), f"{fn} is reachable before the gate"


def test_the_two_protections_are_a_choice_not_a_fallback_after_failure():
    """`sealJSON` must not be wrapped in a try that drops to the shared key.

    That is the shape this would most plausibly grow — "seal if we can, else
    encrypt" reads like resilience — and it would silently store a submission
    under weaker protection than the status endpoint just advertised, on the
    one deployment where the sealed path is broken and nobody is looking.
    """
    body = _submit_handler_code()
    seal = body.index("sealJSON(")
    tail = body[body.index("const payload"):]
    assert "prot.mode === 'sealed'" in tail[:200], (
        "which protection is used must be decided by the mode the gate returned")
    assert "catch" not in body[body.index("const payload"):seal + 200], (
        "a catch around the seal would make the shared key a silent fallback")
